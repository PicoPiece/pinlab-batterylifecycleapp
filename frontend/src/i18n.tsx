const dictionaries: Record<Lang, Dictionary> = { vi, en };

interface I18nContextValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  locale: string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

function initialLang(): Lang {
  if (typeof window === "undefined") return "vi";
  const saved = window.localStorage.getItem("pinlab.lang");
  return saved === "en" ? "en" : "vi";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const initial = initialLang();
    setFormatLocale(initial === "vi" ? "vi-VN" : "en-US");
    return initial;
  });

  const setLang = useCallback((next: Lang) => {
    setFormatLocale(next === "vi" ? "vi-VN" : "en-US");
    setLangState(next);
    if (typeof window !== "undefined") window.localStorage.setItem("pinlab.lang", next);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      let value = dictionaries[lang][key] ?? dictionaries.vi[key] ?? key;
      if (vars) {
        for (const [name, replacement] of Object.entries(vars)) {
          value = value.replaceAll(`{${name}}`, String(replacement));
        }
      }
      return value;
    },
    [lang],
  );

  const value = useMemo(
    () => ({ lang, setLang, t, locale: lang === "vi" ? "vi-VN" : "en-US" }),
    [lang, setLang, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider");
  return context;
}
